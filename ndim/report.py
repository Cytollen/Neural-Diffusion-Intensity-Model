"""``RESULTS.md``: the summary of a run on observations of an unspecified model (``scripts/fit.py``).

It says what was run, gives the main numbers of the evaluation and lists the figures to look at. ``write_results``
builds it from what a finished run holds on disk, so it can be written again after another evaluation.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

import torch

from .config import ExperimentConfig
from .data import Dataset, load_or_generate_dataset
from .links import build_link

NOTES_FILE = "fit_notes.json"
#: a bound (on the diffusion, on the posterior control) that holds on a larger share of the simulated steps is reported
BOUND_SHARE = 0.005


def _fmt(x: Any, digits: int = 4) -> str:
    return "n/a" if x is None else f"{float(x):.{digits}g}"


FIGURES = (
    ("learned_model.png", "the learned prior against the observations (event rate over time, spread between observations, events per "
                          "observation) and the learned drift and diffusion of the intensity"),
    ("training_curves.png", "ELBO, log-likelihood and KL of the training and the test observations, epoch by epoch"),
    ("generated_vs_true_counts.png", "cumulative counts of observations generated by the model against the test observations"),
    ("initial_distribution.png", "the learned distribution of the initial intensity Z_0, and the paths of the burn-in that lead to it"),
    ("posterior_most_events_full.png", "posterior of the intensity given the test observation with the most events: the learned "
                                       "posterior against MCMC under the learned prior"),
    ("posterior_fewest_events_full.png", "the same for the test observation with the fewest events"),
    ("posterior_most_events_partial.png", "the same given only the first half of the window; the prior dynamics continue the path"),
    ("posterior_fewest_events_partial.png", "the same for the test observation with the fewest events"),
)


def _read_json(path: Path) -> Optional[Dict[str, Any]]:
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return None


def _eta_estimate(cfg: ExperimentConfig, run_dir: Path) -> Optional[Dict[str, Any]]:
    """The estimate of the diffusion coefficient saved with the run, if the coefficient of the run is that estimate."""
    est = _read_json(Path(run_dir) / "eta_estimate.json")
    diff = cfg.model.diffusion
    if not est or diff.kind != "cir" or diff.trainable or not isinstance(diff.eta_init, (int, float)):
        return None
    return est if abs(float(est.get("eta", float("nan"))) - float(diff.eta_init)) <= 1e-3 * float(diff.eta_init) else None


def results_summary(cfg: ExperimentConfig, dataset: Dataset, history: List[Dict[str, Any]], best_epoch: int, best_test_elbo: float,
                    run_dir: Path, metrics: Optional[Dict[str, Any]], notes: Sequence[str] = ()) -> str:
    """The text of ``RESULTS.md`` for a run whose training history and evaluation ``metrics`` are given."""
    tr, te = dataset.train, dataset.test
    counts = tr.counts.double()
    burn = cfg.burn_steps * cfg.dt
    diff = cfg.model.diffusion
    if diff.kind == "constant":
        diffusion = f"one learned constant (started at {diff.eta_init:g})" if diff.trainable else f"the constant {diff.eta_init:g}, not trained"
    elif diff.kind == "cir":
        est = _eta_estimate(cfg, run_dir)
        if diff.trainable:
            fixed = f"eta learned (started at {diff.eta_init:g})"
        elif est is None:
            fixed = f"eta = {diff.eta_init:g}, as given and not trained"
        elif est.get("floored"):
            fixed = (f"eta = {diff.eta_init:g}, not trained: the floor, because the training observations show no variation of the "
                     f"intensity on short time scales (95% interval of the estimate: {est['interval'][0]:.3g} to {est['interval'][1]:.3g})")
        else:
            fixed = (f"eta = {diff.eta_init:g}, estimated from the training observations before training (95% interval "
                     f"{est['interval'][0]:.3g} to {est['interval'][1]:.3g}) and not trained")
        diffusion = "eta exp(-X/2), the CIR diffusion eta sqrt(Z) of the intensity, with " + fixed
        if diff.max_step_std is not None:
            if diff.trainable or not isinstance(diff.eta_init, (int, float)):
                floor = "eta^2 dt" + ("" if diff.max_step_std == 1 else f" / {diff.max_step_std:g}^2")
            else:
                floor = f"{float(diff.eta_init) ** 2 * cfg.dt / float(diff.max_step_std) ** 2:.3g}"
            diffusion += (f" (capped at {diff.max_step_std:g} / sqrt(dt), which changes it only below the intensity {floor}: one Euler "
                          f"step then adds noise of standard deviation at most {diff.max_step_std:g} to X)")
    else:
        diffusion = {"mlp": "a network sigma(x, t)" if diff.time_input else "a network sigma(x)"}.get(diff.kind, diff.kind)
        diffusion += "" if diff.trainable else ", not trained"
    skipped = int(sum(h.get("n_skipped", 0) for h in history))
    warm = _read_json(Path(run_dir) / "warm_start.json")
    warm_text = ""
    if warm and warm.get("stages"):
        warm_text = (f" They started from a warm start of {warm['epochs']} epochs, because an untrained model cannot start at this diffusion "
                     f"coefficient: training began at {warm['stages'][0]['eta']:.3g} and the coefficient was raised to "
                     f"{warm['target']:.3g} in {len(warm['stages']) - 1} steps (`warm_start/`).")
    last_eval = max((h["epoch"] for h in history if "test_elbo" in h), default=None)
    lines = [
        f"# Results: {cfg.name}", "",
        "## What was run", "",
        f"- Observations: `{cfg.data.path}`, {len(tr) + len(te)} realisations on [0, {cfg.data.T:g}]: {len(tr)} for training, "
        f"{len(te)} held out for testing. Events per observation: {counts.mean():.1f} on average (from {int(counts.min())} to "
        f"{int(counts.max())} in the training observations).",
        f"- Model: latent state X = log Z ({cfg.model.link} link), drift a network b(x, t), diffusion of X {diffusion}; "
        f"Euler grid of {cfg.data.n_steps} steps (dt = {cfg.dt:g}).",
        (f"- Burn-in: the diffusion starts at t = {-burn:g} from the latent state {float(cfg.model.x_start):.3f} (intensity "
         f"{float(build_link(cfg.model.link)(torch.tensor(float(cfg.model.x_start)))):.3g}), so the distribution of the initial intensity is learned."
         if cfg.burn_steps else f"- No burn-in: every path starts at the fixed intensity {float(cfg.model.z0):.4g}."),
        f"- Input scales: intensity {cfg.model.intensity_scale:g} events per unit time, {cfg.model.posterior.count_scale:g} events per observation.",
        f"- Training: {len(history)} epochs, batch size {cfg.train.batch_size}, {cfg.train.m_paths} Brownian paths per observation, "
        f"horizons {list(cfg.train.horizons)}; best test ELBO {best_test_elbo:.3f} at epoch {best_epoch}"
        + (f"; posterior control bounded at {cfg.train.max_abs_control:g}" if cfg.train.max_abs_control is not None else "")
        + (f"; {skipped} updates were skipped because their loss was not finite" if skipped else "") + "." + warm_text,
        "",
    ]
    remarks = list(notes)
    summary = _read_json(Path(run_dir) / "train_summary.json") or {}
    if summary.get("broke_down_at"):
        remarks.insert(0, f"Training broke down at epoch {summary['broke_down_at']}: from there on no update had a finite loss, because the "
                          f"paths of the model ran off, and training was stopped. The model that is evaluated is the one of epoch "
                          f"{best_epoch}. Two causes are known (`docs/OWN_DATA.md`, Limits). In the first epochs: the networks "
                          "have not yet learned to hold the paths where the intensity is low. The two bounds of the state-space "
                          "parametrization prevent this (`train.max_abs_control`, `model.diffusion.max_step_std`): set them if they "
                          "were switched off, or fit again with another seed (`--set train.seed=2`). Later: a learned drift that "
                          "is too stiff for the Euler step where the intensity is low; fit again with a finer grid (`--steps`).")
    est = _eta_estimate(cfg, run_dir)
    if est is not None and not est.get("floored") and not est.get("determined", True):
        remarks.append(f"The observations determine the coefficient of the diffusion only roughly (95% interval {est['interval'][0]:.3g} to "
                       f"{est['interval'][1]:.3g}; `eta_estimate.png`). Fit again with another value (`--eta`) to see how much the result "
                       "depends on it.")
    if last_eval is not None and best_epoch == last_eval and len(history) > 1:
        remarks.append("The test ELBO was still at its best at the last epoch: training longer may improve the fit (`--epochs`).")
    if metrics:
        lm, sm, ini, post = metrics.get("learned_model") or {}, metrics.get("samples") or {}, metrics.get("initial") or {}, metrics.get("posterior") or {}
        elbo = metrics.get("test_elbo") or {}
        lik = metrics.get("test_likelihood") or {}
        lines += ["## Main numbers", ""]
        if lik:
            d_p, d_g = lik["marginal_minus_poisson"], lik["marginal_minus_poisson_gamma"]
            lines += ["Log-likelihood per test observation (higher is better; differences are taken observation by observation, ± one "
                      "standard error):", "",
                      "| | log-likelihood | learned model minus it |", "|---|---|---|",
                      f"| learned model: marginal log-likelihood (particle filter, {lik['n_particles']} particles) | {lik['marginal_loglik']:.2f} | |",
                      f"| learned model: ELBO (log-likelihood term − KL) | {lik['elbo']:.2f}" + (f" ({_fmt(elbo.get('loglik'), 6)} − {_fmt(elbo.get('kl'), 4)})" if elbo else "")
                      + f" | {lik['elbo_gap']:.2f}, the loss of the amortised posterior |",
                      f"| reference: Poisson process with the event rate of the training observations | {lik['poisson']:.2f} | {d_p['mean']:+.2f} ± {d_p['se']:.2f} |",
                      f"| reference: the same with one gamma factor per observation (its CV: {lik['gamma_factor_cv']:.3f}) | {lik['poisson_gamma']:.2f} | "
                      f"{d_g['mean']:+.2f} ± {d_g['se']:.2f} |", ""]
            if d_p["mean"] < -2.0 * d_p["se"]:
                remarks.append("The learned model has a lower likelihood than a Poisson process with a fixed rate, which has no latent path at all: "
                               "as fitted, the latent intensity does not describe these observations better. Try the other diffusion "
                               "(`--diffusion`), more epochs, or a finer grid (`--steps`).")
            elif d_g["mean"] < -2.0 * d_g["se"]:
                remarks.append("The learned model has a lower likelihood than the Poisson process with one random factor per observation: it has "
                               "not captured a level that differs from one observation to the next and lasts over the window. Look at the "
                               "spread of the number of events per observation in `eval/learned_model.png`.")
            if lik["elbo_gap"] > 10.0:
                remarks.append(f"The ELBO is {lik['elbo_gap']:.1f} nats below the marginal log-likelihood. The posterior shares the diffusion of the "
                               "prior, so on the Euler grid it cannot remove the noise that the diffusion adds in one step; a gap of this size "
                               "says that this noise is large (a large diffusion for the step size). Compare models by the marginal "
                               "log-likelihood.")
        elif elbo:
            lines += [f"Test ELBO per observation (log-likelihood term − KL): {_fmt(elbo.get('elbo'), 6)} ({_fmt(elbo.get('loglik'), 6)} − {_fmt(elbo.get('kl'), 4)}).", ""]
        lines += ["| quantity | learned model | observations |", "|---|---|---|"]
        if sm:
            lines.append(f"| events per observation, mean (test observations) | {_fmt(sm.get('count_mean_generated'))} | {_fmt(sm.get('count_mean_true'))} |")
            lines.append(f"| events per observation, standard deviation | {_fmt(sm.get('count_std_generated'))} | {_fmt(sm.get('count_std_true'))} |")
        if lm:
            lines.append(f"| event rate over time: error of the learned prior, relative to the mean rate | {100 * lm['rate_rmse_relative']:.1f}% | |")
            lines.append(f"| spread between observations of the events per time bin, relative to the observed spread | {lm['count_sd_ratio_mean']:.2f} | 1 |")
            q = lm.get("relative_diffusion_quantiles_5_50_95")
            if q:
                lines.append(f"| diffusion of the intensity per unit of intensity along the prior paths (5%, 50%, 95%) | {_fmt(q[0], 3)}, {_fmt(q[1], 3)}, {_fmt(q[2], 3)} | |")
        for key, value in (metrics.get("learned_scalars") or {}).items():
            lines.append(f"| learned parameter `{key}` | {_fmt(value)} | |")
        if ini and "learned" in ini:
            lines.append(f"| initial intensity Z_0: mean, standard deviation | {_fmt(ini['learned']['mean'])}, {_fmt(ini['learned']['std'])} | "
                         f"event rate at the start of the window {_fmt(ini.get('data_event_rate_at_start'))} |")
        lines.append("")
        cases = post.get("cases") or {}
        if cases:
            lines += ["Learned posterior against MCMC under the learned prior (path Wasserstein-2 distance). Two scales are given: the "
                      "distance between two independent MCMC runs, which is what sampling error alone produces, and the distance from the "
                      "learned prior, which is what ignoring the observation costs. A learned posterior close to the first is as good as "
                      "the reference can tell.", "",
                      "| test observation | conditioned on | events seen | learned posterior to MCMC | between two MCMC runs | learned prior to MCMC |",
                      "|---|---|---|---|---|---|"]
            for key, c in cases.items():
                what, horizon = key.rsplit("_", 1)
                lines.append(f"| {what.replace('_', ' ')} | {'[0, T]' if horizon == 'full' else '[0, ' + _fmt(c.get('t_bar')) + ']'} | {c.get('n_events_observed')} | "
                             f"{_fmt(c.get('w2_vi_vs_reference'))} | {_fmt(c.get('w2_between_two_reference_runs'))} | {_fmt(c.get('w2_prior_vs_reference'))} |")
            lines.append("")
        # a prior without spread and a posterior that does not act: the model has become a Poisson process with a fixed rate
        cv = lm.get("intensity_cv_mean_over_time")
        if cv is not None and cv < 0.02 and elbo.get("kl") is not None and float(elbo["kl"]) < 0.05:
            remarks.insert(0, f"The model has collapsed to a Poisson process with a fixed rate: the intensity of the learned prior does not "
                              f"vary between paths (coefficient of variation {cv:.3f}) and the posterior correction is switched off (KL "
                              f"{float(elbo['kl']):.3f}). The diffusion was trained down to nothing before the posterior had learned to use it, "
                              "and training does not come back from there. See `docs/OWN_DATA.md`, Limits.")
        from .metrics import STIFF_SHARE

        gain = lm.get("euler_gain") or {}
        if (gain.get("share_below_minus_one") or 0.0) > STIFF_SHARE:
            where = ("on the burn-in" if (gain.get("share_below_minus_one_burn_in") or 0.0) > 4 * (gain.get("share_below_minus_one_window") or 0.0)
                     else "on the observation window" if (gain.get("share_below_minus_one_window") or 0.0) > 4 * (gain.get("share_below_minus_one_burn_in") or 0.0)
                     else "on the burn-in and on the window")
            remarks.append(f"The learned drift is too stiff for the Euler grid on {100 * gain['share_below_minus_one']:.1f}% of the steps of "
                           f"the prior paths, mostly {where}: one step turns a small deviation of the state into a larger one of the "
                           f"opposite sign there (gain 1 + dt db/dx below -1, smallest {gain['min']:.2f}). Such a fit is fragile, and "
                           "training on this grid can break down. Fit again with a finer grid (`--steps`).")
        bounds = (metrics.get("test_elbo") or {}).get("bounds") or {}
        share = max(bounds.get("diffusion_bound_share") or 0.0, lm.get("diffusion_bound_share") or 0.0)
        if share > BOUND_SHARE:
            remarks.append(f"The bound on the diffusion holds on {100 * share:.1f}% of the steps of the simulated paths: the intensity is "
                           f"below eta^2 dt there, and the diffusion of the model is not the CIR form at those states. A finer grid "
                           "(`--steps`) lowers that intensity.")
        if (bounds.get("control_bound_share") or 0.0) > BOUND_SHARE:
            remarks.append(f"The bound on the posterior control ({bounds.get('control_bound'):g}) holds on "
                           f"{100 * bounds['control_bound_share']:.1f}% of the steps of the posterior paths: the posterior network asks for "
                           "larger corrections than the bound allows, which a fitted model does not do (`docs/REAL_STATE_LINKS.md`). "
                           "Train longer, or look at the posterior figures before using the model.")
        for err in metrics.get("errors") or []:
            remarks.append(f"The evaluation stage `{err.get('stage')}` failed: {err.get('error')} (see `eval/eval.log`).")
        if lm.get("n_nonfinite_prior_paths"):
            remarks.append(f"{lm['n_nonfinite_prior_paths']} of {lm['n_prior_paths'] + lm['n_nonfinite_prior_paths']} paths of the learned prior were not finite.")
    if remarks:
        lines += ["## Remarks", ""] + [f"- {r}" for r in remarks] + [""]
    eval_dir = Path(run_dir) / "eval"
    present = [(name, text) for name, text in FIGURES if (eval_dir / name).exists()]
    if present:
        lines += ["## Figures", ""] + [f"- `eval/{name}`: {text}." for name, text in present] + [""]
        lines += [f"![the learned model](eval/{present[0][0]})", ""]
    lines += ["## Files", "", "- `eval/metrics.json`: every number of the evaluation; `eval/eval.log`: its log.",
              "- `ckpt_best.pt`: the trained model at its best test ELBO (`ckpt_last.pt`: at the last epoch); load it with "
              "`ndim.model.NDIM.load_checkpoint`.",
              "- `config.yaml`: the settings of this run, with everything that was set from the data; `train.log`, `history.csv`: the training.",
              ] + (["- `eta_estimate.png`, `eta_estimate.json`: the estimate of the diffusion coefficient at every bin width, and its fit."]
                   if (Path(run_dir) / "eta_estimate.json").exists() else []) + [
              "- Evaluate again, for instance with a longer MCMC: `python scripts/evaluate.py --run " + str(run_dir) + " --set eval.mcmc.n_steps=20000` "
              "(this file is then written again).", ""]
    return "\n".join(lines)


def write_results(run_dir: Path, notes: Optional[Sequence[str]] = None) -> Optional[Path]:
    """Write ``run_dir/RESULTS.md`` from what the run holds on disk: its config, its training history and, when it
    was evaluated, ``eval/metrics.json``. ``notes`` (remarks made when the run was set up) are stored with the run
    and reused when the file is written again. Returns ``None`` for a run on synthetic data, which has its own
    figures against the truth."""
    from .evaluate import load_eval_config

    run_dir = Path(run_dir)
    cfg = load_eval_config(run_dir)
    if cfg.data.source != "file":
        return None
    notes_path = run_dir / NOTES_FILE
    if notes is not None:
        notes_path.write_text(json.dumps(list(notes), indent=1))
    elif notes_path.exists():
        notes = json.loads(notes_path.read_text())
    dataset, _ = load_or_generate_dataset(cfg)
    history = json.loads((run_dir / "history.json").read_text())
    if (run_dir / "train_summary.json").exists():
        summary = json.loads((run_dir / "train_summary.json").read_text())
        best_epoch, best_elbo = int(summary["best_epoch"]), float(summary["best_test_elbo"])
    else:                                   # a run that is still training or was stopped: the best epoch evaluated so far
        evaluated = [h for h in history if "test_elbo" in h]
        best = max(evaluated, key=lambda h: h["test_elbo"]) if evaluated else {"epoch": 0, "test_elbo": float("nan")}
        best_epoch, best_elbo = int(best["epoch"]), float(best["test_elbo"])
    metrics_path = run_dir / "eval" / "metrics.json"
    metrics = json.loads(metrics_path.read_text()) if metrics_path.exists() else None
    path = run_dir / "RESULTS.md"
    path.write_text(results_summary(cfg, dataset, history, best_epoch, best_elbo, run_dir, metrics, notes or ()))
    return path
